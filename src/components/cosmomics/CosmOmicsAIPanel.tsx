'use client';

import { useEffect, useId, useRef, useState } from 'react';
import Link from 'next/link';
import { Loader2, ShieldCheck, Sparkles } from 'lucide-react';
import {
  useCosmOmicsInterpretation,
  useCosmOmicsSavedInterpretation,
} from '@/hooks/useCosmOmicsNova';
import { useUserProfile } from '@/hooks/useUserProfile';
import AIMarkdown from '@/components/ui/AIMarkdown';
import {
  AI_QUOTA_COPY,
  PLAN_GATE_COPY,
  UPGRADE_HREF,
  aiQuotaMessage,
  apiErrorMessage,
  canUseAI,
  isAiQuotaExhausted,
} from '@/utils/plan';
import { NOVA_INK } from './novaPalette';
import { DEFAULT_ALPHA, aiLabel } from './novaText';

interface Props {
  datasetId?: string;
  comparisonName?: string;
  /** The nova's own threshold: a saved text is `stale` when it was written for another one. */
  alpha?: number;
  disabled?: boolean;
}

/**
 * What leaves for the model, said before the first call. It mirrors what the backend's
 * prompt carries: claim and sub-group names, their direction and side, counts, p-values.
 *
 * It takes focus when it opens, and what is sent is its accessible description, so a screen
 * reader announces it and a keyboard user lands on it; Escape cancels. The caller gives
 * focus back to the trigger on Cancel, Escape and Agree.
 */
function Consent({
  model,
  onAgree,
  onCancel,
}: {
  model?: string;
  onAgree: () => void;
  onCancel: () => void;
}) {
  const ref = useRef<HTMLElement>(null);
  const sentId = useId();
  const notSentId = useId();
  useEffect(() => ref.current?.focus(), []);
  return (
    <section
      ref={ref}
      tabIndex={-1}
      aria-label="Before the AI is called"
      aria-describedby={`${sentId} ${notSentId}`}
      onKeyDown={(event) => {
        if (event.key === 'Escape') {
          event.stopPropagation();
          onCancel();
        }
      }}
      className="mb-3 space-y-2 rounded-card border border-subtle bg-surface-2 p-3 text-body-sm text-primary outline-none focus-visible:ring-2 focus-visible:ring-[var(--sl-teal-dark)]"
    >
      <p className="font-semibold">Before the AI is called</p>
      <p id={sentId}>
        This reading is written by a hosted language model. What is sent: the names of the claims and of their
        pathway sub-groups, the direction of each sub-group (up or down) and its side (for, against or balanced),
        the counts of sub-groups per side, and their p-values. Only the strongest claims and sub-groups fit in the
        request.
      </p>
      <p id={notSentId}>Not sent: the comparison name, any gene list, any identifier or setting, your raw data.</p>
      <p>
        {model
          ? `Model: ${model}, the one that wrote the saved text. `
          : 'The model is named on the text once it is written. '}
        Writing it uses one AI request.
      </p>
      <div className="flex flex-wrap gap-2 pt-1">
        <button
          type="button"
          onClick={onAgree}
          className="rounded-control px-3 py-1.5 text-caption font-medium text-on-accent"
          style={{ background: 'var(--sl-teal-dark)' }}
        >
          Agree and generate
        </button>
        <button
          type="button"
          onClick={onCancel}
          className="rounded-control border border-subtle px-3 py-1.5 text-caption font-medium text-secondary"
        >
          Cancel
        </button>
      </div>
    </section>
  );
}

/**
 * AI cosmetic reading of the nova. Nothing is sent to the model until the user agrees,
 * once per visit, to what is sent. A text already saved is read, never regenerated by
 * opening the panel; it carries the model and the day it was written, and says so when
 * it was written from other results than the ones on screen.
 */
export default function CosmOmicsAIPanel({ datasetId, comparisonName, alpha = DEFAULT_ALPHA, disabled }: Props) {
  const { data: profile } = useUserProfile();
  const allowed = canUseAI(profile);
  // Both AI routes need AI access: without it nothing is asked of the server.
  const saved = useCosmOmicsSavedInterpretation(datasetId, comparisonName, alpha, allowed);
  const mutation = useCosmOmicsInterpretation(datasetId, comparisonName, alpha);
  const [agreed, setAgreed] = useState(false);
  const [asking, setAsking] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);

  const reading = allowed ? (saved.data ?? null) : null;
  const stale = reading?.stale === true;

  // A text is saved: the user asked for a new one, so the server must not serve the old one.
  const generate = () => mutation.mutate(!!reading);
  const request = () => (agreed ? generate() : setAsking(true));
  // The consent unmounts on Agree, Cancel and Escape: focus goes back to the trigger first, so it is
  // never left on a button that is about to disappear.
  const cancel = () => {
    triggerRef.current?.focus();
    setAsking(false);
  };
  const agree = () => {
    triggerRef.current?.focus();
    setAgreed(true);
    setAsking(false);
    generate();
  };

  const error = mutation.error ?? saved.error;
  const quotaExhausted = isAiQuotaExhausted(error);
  const errMsg = error ? (quotaExhausted ? aiQuotaMessage(error) : apiErrorMessage(error)) : null;
  const busy = mutation.isPending;
  const claimsCut =
    reading && reading.claims_sent != null && reading.claims_total != null && reading.claims_sent < reading.claims_total;

  return (
    <div className="gl-card p-4">
      <div className="mb-3 flex items-center justify-between gap-3">
        <h3 className="flex items-center gap-2 text-body-sm font-semibold text-primary">
          <Sparkles className="h-4 w-4" style={{ color: NOVA_INK.green }} aria-hidden />
          AI cosmetic reading
        </h3>
        <button
          ref={triggerRef}
          type="button"
          // Busy and asking are transient: `aria-disabled` keeps the trigger focusable, so focus can come back to it.
          onClick={() => !busy && !asking && request()}
          disabled={disabled || !allowed || saved.isLoading}
          aria-disabled={busy || asking || undefined}
          className="flex items-center gap-2 rounded-control px-3 py-1.5 text-caption font-medium text-on-accent disabled:opacity-50 aria-disabled:opacity-50"
          style={{ background: 'var(--sl-teal-dark)' }}
        >
          {busy ? (
            <>
              <Loader2 className="h-3.5 w-3.5 animate-spin" /> Generating…
            </>
          ) : reading ? (
            'Regenerate'
          ) : (
            'Generate interpretation'
          )}
        </button>
      </div>

      {!allowed && (
        <p className="mb-3 text-body-sm text-secondary">
          {PLAN_GATE_COPY.ai}{' '}
          <Link href={UPGRADE_HREF} className="font-medium underline">
            View plans
          </Link>
        </p>
      )}

      {asking && <Consent model={reading?.model} onAgree={agree} onCancel={cancel} />}

      {busy && (
        <p className="text-caption text-secondary">
          The AI is reading the pathways for and against each claim — this can take 15–60 seconds.
        </p>
      )}
      {errMsg && quotaExhausted && (
        <p className="text-body-sm text-warning-ink">
          <span className="font-semibold">{AI_QUOTA_COPY.title}.</span> {errMsg}
        </p>
      )}
      {errMsg && !quotaExhausted && <p className="text-body-sm text-danger-ink">{errMsg}</p>}

      {reading ? (
        <div>
          {stale && (
            <p role="status" className="mb-2 rounded-control bg-warning-soft px-3 py-2 text-caption text-warning-ink">
              <span className="font-semibold">Out of date.</span> This text was written from other results than the
              ones shown (another threshold, referential or enrichment). Regenerate it to read the current nova.
            </p>
          )}
          <div className={stale ? 'opacity-60' : undefined}>
            <AIMarkdown text={reading.interpretation} />
          </div>
          <p className="mt-2 text-micro text-secondary">{aiLabel(reading.model, reading.generated_at)}</p>
          {claimsCut && (
            <p className="mt-1 text-micro text-secondary">
              Covers {reading.claims_sent} of {reading.claims_total} claims.
            </p>
          )}
        </div>
      ) : (
        !busy &&
        !asking &&
        allowed && (
          <p className="text-body-sm text-secondary">
            A reading of the nova, claim by claim, with a short summary. It restates the data above and adds
            nothing to them. Nothing is sent to the AI until you agree.
          </p>
        )
      )}

      <div className="mt-4 flex items-start gap-2 border-t border-subtle pt-3 text-micro text-secondary">
        <ShieldCheck className="mt-1 h-3.5 w-3.5 shrink-0" />
        Cosmetic effects only — not medical or therapeutic claims. AI-generated text: check it against the data
        before using it.
      </div>
    </div>
  );
}
